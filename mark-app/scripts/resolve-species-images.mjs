const DISPLAY_NAMES = { ...SPECIES }

const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

function upscaleThumb(url) {
  if (!url) return null
  return url.replace(/\/(\d+)px-/, '/800px-')
}

async function wikiPhoto(title) {
  const url = `https://en.wikipedia.org/api/rest_v1/page/summary/${encodeURIComponent(title)}`
  const res = await fetch(url, {
    headers: { 'User-Agent': 'MarkApp/1.0 (species reference; contact@example.com)' },
  })
  if (!res.ok) return null
  const data = await res.json()
  const thumb = data?.thumbnail?.source
  const original = data?.originalimage?.source
  if (original && /\.(jpe?g|png|webp)$/i.test(original)) return original
  return upscaleThumb(thumb)
}

async function commonsSearch(query) {
  const params = new URLSearchParams({
    action: 'query',
    format: 'json',
    origin: '*',
    generator: 'search',
    gsrsearch: `filetype:bitmap ${query}`,
    gsrnamespace: '6',
    gsrlimit: '3',
    prop: 'imageinfo',
    iiurlwidth: '800',
  })
  const res = await fetch(`https://commons.wikimedia.org/w/api.php?${params}`, {
    headers: { 'User-Agent': 'MarkApp/1.0 (species reference)' },
  })
  if (!res.ok) return null
  const data = await res.json()
  const pages = data?.query?.pages
  if (!pages) return null
  for (const page of Object.values(pages)) {
    const url = page.imageinfo?.[0]?.thumburl
    if (url) return url
  }
  return null
}

async function resolve(id, title) {
  let src = await wikiPhoto(title)
  if (!src) src = await commonsSearch(title)
  return src
}

async function main() {
  const resolved = {}
  const failed = []

  for (const [id, title] of Object.entries(SPECIES)) {
    process.stderr.write(`… ${id}\n`)
    try {
      const src = await resolve(id, title)
      if (src) {
        resolved[id] = { src, alt: DISPLAY_NAMES[id] ?? title }
      } else {
        failed.push(id)
      }
    } catch {
      failed.push(id)
    }
    await sleep(800)
  }

  const out = `/**
 * AUTO-GENERATED by scripts/resolve-species-images.mjs
 * Real photograph URLs (Wikipedia / Wikimedia Commons).
 * Regenerate: node scripts/resolve-species-images.mjs
 */

export type SpeciesImageMeta = {
  src: string
  alt: string
  credit?: string
}

const CREDIT = 'Photo: Wikimedia Commons'

const SPECIES_IMAGES: Record<string, SpeciesImageMeta> = {
${Object.entries(resolved)
  .map(
    ([id, { src, alt }]) =>
      `  '${id}': { src: ${JSON.stringify(src)}, alt: ${JSON.stringify(alt)}, credit: CREDIT },`,
  )
  .join('\n')}
}

function slugify(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
}

export function getSpeciesImage(id: string, name: string): SpeciesImageMeta | null {
  const byId = SPECIES_IMAGES[id]
  if (byId) return byId
  const bySlug = SPECIES_IMAGES[slugify(name)]
  if (bySlug) return { ...bySlug, alt: name }
  return null
}
`

  writeFileSync(join(__dirname, '../src/data/speciesImages.ts'), out)
  console.log(`Resolved ${Object.keys(resolved).length}/${Object.keys(SPECIES).length}`)
  if (failed.length) console.log('Still missing:', failed.join(', '))
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
