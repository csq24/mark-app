export function zoomExplorerTier(zoom: number): {
  id: string
  label: string
  hint: string
} {
  if (zoom < 3) {
    return {
      id: 'world',
      label: 'World view',
      hint: 'Tap a flag to see country fishing highlights',
    }
  }
  if (zoom < 5.5) {
    return {
      id: 'countries',
      label: 'Countries',
      hint: 'Zoom in for regions & famous fishing areas',
    }
  }
  if (zoom < 7) {
    return {
      id: 'regions',
      label: 'Regions',
      hint: 'Zoom in for specific coasts & bays',
    }
  }
  if (zoom < 10) {
    return {
      id: 'coasts',
      label: 'Specific coasts',
      hint: 'Tap a coast for local species — Tampa Bay, Keys, Outer Banks…',
    }
  }
  if (zoom < 12) {
    return {
      id: 'local',
      label: 'Harbors & bays',
      hint: 'Drop marks on reefs, flats, or your secret hole',
    }
  }
  return {
    id: 'spot',
    label: 'Your Mark',
    hint: 'Mark here — long-press or use the crosshair button',
  }
}
